import { launchBrowser, acquireLock, releaseLock } from './browser.mjs';
import fs from 'node:fs';
await acquireLock();
const { browser } = await launchBrowser();
const page = await browser.newPage({ viewport: { width: 640, height: 360 } });
await page.routeWebSocket(/.*/, () => {});
await page.goto('http://127.0.0.1:5173/?nointro&noidle');
await page.waitForFunction(() => window.__city && window.__city.ctx && window.__city.modules, null, { timeout: 300000 });
await page.waitForTimeout(8000);
const d = await page.evaluate(() => {
  const c = window.__city.ctx, p = c.plan;
  const ctr = (r) => r ? [(r.x0 + r.x1) / 2, (r.z0 + r.z1) / 2, r.x1 - r.x0, r.z1 - r.z0] : null;
  const out = {};
  out.areas = p.areas.map((a) => [a.kind, ...ctr(a.rect).map((v) => +v.toFixed(1))]);
  out.features = p.features.map((f) => [f.kind, +f.x.toFixed(1), +f.z.toFixed(1), +f.yaw.toFixed(2)]);
  out.slots = p.slots.map((s) => [s.kind, +s.x.toFixed(1), +s.z.toFixed(1), +s.yaw.toFixed(2)]);
  out.lots = p.lots.map((l) => [l.kind, ...(l.footprint ? ctr(l.footprint).map((v) => +v.toFixed(1)) : [])]);
  const named = {};
  c.scene.traverse((o) => { if (o.name) named[o.name] = (named[o.name] || 0) + 1; });
  out.named = named;
  const fs = [];
  c.scene.traverse((o) => { if (o.name === 'land-farmstead') { o.geometry.computeBoundingSphere(); const s = o.geometry.boundingSphere; const v = s.center.clone().applyMatrix4(o.matrixWorld); fs.push([+v.x.toFixed(1), +v.y.toFixed(1), +v.z.toFixed(1), +s.radius.toFixed(1)]); } });
  out.farmsteads = fs;
  const fl = c.scene.getObjectByName('land-farmlife');
  const h = fl?.userData.herd || [];
  const herd = []; for (let i = 0; i < h.length; i += 7) herd.push([+h[i].toFixed(1), +h[i + 1].toFixed(1), +h[i + 2].toFixed(1), h[i + 4]]);
  out.herd = herd;
  out.boats = (c.services.boats?.fleet?.boats || []).map((b) => [b.kind || b.type || '?', +(b.x ?? b.pos?.x ?? 0).toFixed?.(1), +(b.z ?? b.pos?.z ?? 0).toFixed?.(1)]);
  out.cafes = (c.services.props?.cafes || []).slice(0, 40).map((t) => [+(t.x ?? 0).toFixed(1), +(t.z ?? 0).toFixed(1)]);
  out.pois = p.pois.map((q) => [q.id, q.target?.x ?? q.x, q.target?.z ?? q.z]);
  return out;
});
fs.writeFileSync('/tmp/claude-0/-home-user-GameCity/84ce0e16-d912-5b31-a3c0-249b824f7685/scratchpad/plan.json', JSON.stringify(d));
await browser.close(); releaseLock();
console.log(Object.keys(d).map((k) => k + ':' + (Array.isArray(d[k]) ? d[k].length : Object.keys(d[k]).length)).join(' '));
