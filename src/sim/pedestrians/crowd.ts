/** Spatial hash of obstacles (members + their prams/dogs). */
class Grid {
  readonly cell = 2;
  readonly x0 = SLAB.x0 - 20;
  readonly z0 = SLAB.z0 - 20;
  readonly w: number;
  readonly h: number;
  head: Int32Array;
  next = new Int32Array(1024);
  ox: number[] = [];
  oz: number[] = [];
  ovx: number[] = [];
  ovz: number[] = [];
  /** facing direction of the person (or of the walker of a dog / pram) */
  ohx: number[] = [];
  ohz: number[] = [];
  or: number[] = [];
  op: number[] = [];
  om: (Member | null)[] = [];
  n = 0;
  private touched: number[] = [];
  constructor() {
    this.w = Math.ceil((SLAB.x1 - SLAB.x0 + 40) / this.cell);
    this.h = Math.ceil((SLAB.z1 - SLAB.z0 + 40) / this.cell);
    this.head = new Int32Array(this.w * this.h).fill(-1);
  }
  clear(): void {
    for (const c of this.touched) this.head[c] = -1;
    this.touched.length = 0;
    this.n = 0;
  }
  add(x: number, z: number, vx: number, vz: number, r: number, party: number, m: Member | null, hx = 0, hz = 0): void {
    const i = Math.floor((x - this.x0) / this.cell),
      j = Math.floor((z - this.z0) / this.cell);
    if (i < 0 || j < 0 || i >= this.w || j >= this.h) return;
    const c = j * this.w + i;
    const k = this.n++;
    if (k >= this.next.length) {
      const nn = new Int32Array(this.next.length * 2);
      nn.set(this.next);
      this.next = nn;
    }
    this.ox[k] = x;
    this.oz[k] = z;
    this.ovx[k] = vx;
    this.ovz[k] = vz;
    this.ohx[k] = hx;
    this.ohz[k] = hz;
    this.or[k] = r;
    this.op[k] = party;
    this.om[k] = m;
    if (this.head[c] === -1) this.touched.push(c);
    this.next[k] = this.head[c];
    this.head[c] = k;
  }
  /** iterate obstacle indices within the box around (x, z) */
  each(x: number, z: number, r: number, fn: (k: number) => void): void {
    const i0 = Math.max(0, Math.floor((x - r - this.x0) / this.cell)),
      i1 = Math.min(this.w - 1, Math.floor((x + r - this.x0) / this.cell));
    const j0 = Math.max(0, Math.floor((z - r - this.z0) / this.cell)),
      j1 = Math.min(this.h - 1, Math.floor((z + r - this.z0) / this.cell));
    for (let j = j0; j <= j1; j++) {
      for (let i = i0; i <= i1; i++) {
        for (let k = this.head[j * this.w + i]; k !== -1; k = this.next[k]) fn(k);
      }
    }
  }
}

