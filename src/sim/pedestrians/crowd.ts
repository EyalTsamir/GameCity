// The pedestrian simulation.
//
// People move in small parties (1–3 members: singles, couples, families) that
// follow "rails" (smoothed, offset routes over the pedestrian graph). A party's
// life: emerge from a door / bus / station → walk to a goal (bench, beach towel,
// viewpoint, bus stop, waypoints for strolls & jogs) → act there → continue → step
// into a door (or board a bus). Crosswalks use the IntersectionManager protocol
// (wait at the corner, canCross → beginCross → endCross). Local avoidance shifts
// a party sideways inside its walkway band or slows it down; it never leaves the
// band, so nobody walks through buildings, water, props or roads.
//
// Avoidance (see avoid()): every walking party knows its own footprint (members side
// by side or in file, plus the dog on the walker's left or the pram in front). Each
// person / dog / pram of another party within the look-ahead window blocks an
// interval of lateral offsets. The most urgent conflicts are removed from the free
// lateral band first and the party steers to the nearest free offset (keeping its
// side when it can; oncoming people both step away from each other). Whatever it
// cannot dodge in time it follows or stops for (speed cap from the free gap), the
// party behind always yields to the one in front, side-by-side parties close up into
// single file to let others pass, and nobody ever walks through anybody to get unstuck.
// Short free walks (to a corner spot, a seat, the bus door…) wait for people in the way.

