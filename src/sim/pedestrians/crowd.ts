const clamp = (v: number, a: number, b: number) => (v < a ? a : v > b ? b : v);
/** is a disc (x, z, r) inside one of the crossing arrival lanes from Crowd.arrivalLanes()? */
function inLanes(lanes: number[], x: number, z: number, r: number): boolean {
  for (let i = 0; i < lanes.length; i += 4) {
    const rx = x - lanes[i],
      rz = z - lanes[i + 1];
    const dx = lanes[i + 2],
      dz = lanes[i + 3];
    const u = rx * dx + rz * dz,
      l = -rx * dz + rz * dx;
    if (u > -0.3 - r && u < 1.9 + r && l > -1.05 - r && l < 0.05 + r) return true;
  }
  return false;
}

/** index of the rail leg current at arc length s (legs are contiguous in s) */
function legAt(r: Rail, s: number): number {
  const legs = r.legs;
  for (let i = 0; i < legs.length - 1; i++) if (s < legs[i].s1) return i;
  return legs.length - 1;
}
const smooth = (t: number) => t * t * (3 - 2 * t);
function angleDiff(a: number, b: number): number {
  let d = (b - a) % (Math.PI * 2);
  if (d > Math.PI) d -= Math.PI * 2;
  if (d < -Math.PI) d += Math.PI * 2;
  return d;
}

const POP = [0.12, 0.08, 0.06, 0.05, 0.06, 0.12, 0.3, 0.62, 0.84, 0.78, 0.84, 0.92, 1, 1, 0.94, 0.92, 0.96, 1, 1, 0.94, 0.84, 0.66, 0.46, 0.26];
function popFactor(h: number): number {
  const i = Math.floor(h) % 24;
  const f = h - Math.floor(h);
  return POP[i] * (1 - f) + POP[(i + 1) % 24] * f;
}
function bump(h: number, a: number, b: number, fade = 1): number {
  if (h < a - fade || h > b + fade) return 0;
  if (h < a) return smooth((h - (a - fade)) / fade);
  if (h > b) return smooth(1 - (h - b) / fade);
  return 1;
}
function beachFactor(h: number): number {
  return bump(h, 10.5, 17, 1.5);
}
